"""Drop-rate sweep over pearl_street_peak: 1%, 5% and 10%, 20 seeds each, three message sets.

    python examples/pearl_street/fault_sweep.py          # writes fault_sweep_results.md

Each run is the base scenario with Town's `drop_rate` fault and a different
seed (the seed only drives which messages drop; no agent uses randomness).
The fault applies to one of three message sets:

- all messages;
- telemetry only: the meter's readings to the exchange (Pearl Street's
  settlement rule alone: a missing reading counts as zero delivery);
- award and meter_request only: the chain by which this example's meter
  learns what to read (the operator forwards each award to the meter).

Runs use the Lab engine directly and write no bundles. Per cell it reports
the share of runs where:

- an honest provider (no planted behaviour) was charged a shortfall or
  rated bad: the validator's honest_providers_unharmed stage failed;
- the overpromiser (pvb-35) was still caught: it was settled with a
  shortfall charge and rated bad;
- the ledger stayed conserved: Town's ledger_conserved stage passed.

The output is deterministic: the same Town and Pearl Street commits give the
same table.
"""

from __future__ import annotations

import os
import sys
from collections import Counter

from nandatown.sim.runner import build_engine, load_plugin_files
from nandatown.sim.scenario import FaultRule, load_scenario_file
from nandatown.sim.validators import evaluate_scenario

HERE = os.path.dirname(os.path.abspath(__file__))
BASE = os.path.join(HERE, "pearl_street_peak.yaml")
OUT = os.path.join(HERE, "fault_sweep_results.md")
RATES = [0.01, 0.05, 0.10]
SEEDS = range(1, 21)
OVERPROMISER = "pvb-35"
MESSAGE_SETS = [
    ("all messages", None),
    ("telemetry only", ["telemetry"]),
    ("award and meter_request only", ["award", "meter_request"]),
]


def one_run(base, rate: float, seed: int, kinds: list[str] | None = None) -> dict:
    spec = base.model_copy(deep=True)
    spec.seed = seed
    spec.faults = ([FaultRule(action="drop_rate", rate=rate)] if kinds is None
                   else [FaultRule(action="drop_rate", rate=rate, kind=k) for k in kinds])
    engine = build_engine(spec)
    engine.run()
    events = engine.events
    result = evaluate_scenario(spec, engine.run_id, events)
    status = {s.name: s.status for s in result.stages}
    notes = {s.name: s.note for s in result.stages}
    settle = [e for e in events if e.kind == "pearl_settle" and e.subject == OVERPROMISER]
    rated_bad = any(e.kind == "reputation_updated" and e.subject == OVERPROMISER
                    and e.detail.get("outcome") == "bad" for e in events)
    awarded = any(e.kind == "pearl_award" and e.subject == OVERPROMISER for e in events)
    caught = bool(settle) and settle[0].detail["charge_usd"] > 0 and rated_bad
    dropped = Counter(e.detail["kind"] for e in events if e.kind == "message_dropped")
    return {
        "rate": rate, "seed": seed, "kinds": kinds,
        "dropped": sum(dropped.values()), "dropped_kinds": dict(sorted(dropped.items())),
        "honest_harmed": status.get("honest_providers_unharmed") == "failed",
        "harm_note": notes.get("honest_providers_unharmed", "")
        if status.get("honest_providers_unharmed") == "failed" else "",
        "overpromiser_awarded": awarded,
        "overpromiser_caught": caught,
        "ledger_conserved": status.get("ledger_conserved") == "passed",
    }


def pct(n: int, d: int) -> str:
    return f"{n}/{d} ({100 * n / d:.0f}%)"


def render() -> str:
    base = load_scenario_file(BASE)
    load_plugin_files(base.plugin_files)
    runs = {label: [one_run(base, r, s, kinds) for r in RATES for s in SEEDS]
            for label, kinds in MESSAGE_SETS}

    lines = [
        "# Drop-rate sweep: pearl_street_peak",
        "",
        "Generated by `fault_sweep.py`; do not edit. Town fault `drop_rate`, seeds",
        f"{SEEDS.start}-{SEEDS.stop - 1} per rate, on one message set at a time. Honest = dc-08 and",
        "pvb-48 (no planted behaviour). Caught = the overpromiser pvb-35 was settled with a",
        "shortfall charge and rated bad. With 20 runs per cell, a share has a standard error",
        "of roughly 11 percentage points at 50%.",
        "",
        "| messages dropped | drop rate | runs | mean dropped | honest provider charged or rated down"
        " | overpromiser awarded | overpromiser still caught | ledger conserved |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for label, _ in MESSAGE_SETS:
        for rate in RATES:
            cell = [x for x in runs[label] if x["rate"] == rate]
            n = len(cell)
            lines.append(
                f"| {label} | {rate:.0%} | {n} | {sum(x['dropped'] for x in cell) / n:.1f} | "
                f"{pct(sum(x['honest_harmed'] for x in cell), n)} | "
                f"{pct(sum(x['overpromiser_awarded'] for x in cell), n)} | "
                f"{pct(sum(x['overpromiser_caught'] for x in cell), n)} | "
                f"{pct(sum(x['ledger_conserved'] for x in cell), n)} |")
    lines += ["", "## Runs where an honest provider was harmed", "",
              "| messages dropped | drop rate | seed | dropped (by kind) | validator note |",
              "|---|---|---|---|---|"]
    for label, _ in MESSAGE_SETS:
        for x in runs[label]:
            if x["honest_harmed"]:
                kinds = ", ".join(f"{k} {v}" for k, v in x["dropped_kinds"].items())
                lines.append(f"| {label} | {x['rate']:.0%} | {x['seed']} | {kinds} | {x['harm_note']} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    text = render()
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    sys.stdout.write(text)


if __name__ == "__main__":
    main()
