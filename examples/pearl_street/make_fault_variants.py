"""Write the fault-injection variants of pearl_street_peak.yaml.

Each variant is the base scenario (same roster, same Engie slice, same seed)
with one Town transport fault added under `faults:`. They share the base's
validator. Regenerate after editing the base:

    python examples/pearl_street/make_fault_variants.py
"""

from __future__ import annotations

import os

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
BASE = os.path.join(HERE, "pearl_street_peak.yaml")

# Town counts a rule's matches per message kind across all senders.
# telemetry #1 is the meter's first reading of the first award (pvb-48 at
# 22:00 UTC); offer #1 is dc-08's offer, the first one sent (20:20 UTC).
VARIANTS = {
    "drop": {
        "faults": [{"action": "drop", "kind": "telemetry", "nth": 1}],
        "question": "One of pvb-48's 12 meter readings is lost. Does settlement treat it as"
                    " under-delivery and charge an honest provider?",
    },
    "duplicate": {
        "faults": [{"action": "duplicate", "kind": "offer", "nth": 1}],
        "question": "dc-08's offer is delivered twice. Does clearing count it twice or"
                    " dedupe it?",
    },
    "delay": {
        "faults": [{"action": "delay", "kind": "offer", "nth": 1, "delay": 45}],
        "question": "dc-08's offer, sent at 20:20 UTC (gate 21:00), arrives at 21:05. Is it"
                    " rejected, and whose time decides: send or arrival?",
    },
}


def variant(base: dict, key: str) -> dict:
    v = VARIANTS[key]
    out = dict(base)
    out["name"] = f"{base['name']}_{key}"
    out["description"] = f"{base['name']} with one injected {key} fault. {v['question']}"
    out["validator"] = base["name"]
    out["faults"] = v["faults"]
    return out


def main() -> None:
    with open(BASE, encoding="utf-8") as f:
        base = yaml.safe_load(f)
    for key in VARIANTS:
        path = os.path.join(HERE, f"pearl_street_peak_{key}.yaml")
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(f"# Generated by make_fault_variants.py from pearl_street_peak.yaml;"
                    f" do not edit.\n")
            yaml.safe_dump(variant(base, key), f, sort_keys=False, width=100)
        print(path)


if __name__ == "__main__":
    main()
