"""Write the repeat-event scenarios from pearl_street_peak.yaml.

Two back-to-back evening needs (2023-07-25 and 2023-07-26, 17:00-20:00
Central), same roster, same Engie slice, same offers on both days. Arms:

- pearl_street_repeat.yaml: no feedback. Nothing that happens on day one
  changes who can win on day two.
- pearl_street_repeat_policy.yaml: before each need, the utility asks the
  exchange's Town gateway to refuse offers from providers whose Town
  reputation is below zero (enforced in Town, not by Pearl Street).

A third arm, Pearl Street's own delivery-record limits, is not generated:
its `delivery_record` option records binding-nomination delivery and, by its
own documentation, never charges or limits awards, so no exchange setting
turns the record into an award limit.

    python examples/pearl_street/make_repeat_scenarios.py
"""

from __future__ import annotations

import copy
import os
from datetime import datetime, timedelta, timezone

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
BASE = os.path.join(HERE, "pearl_street_peak.yaml")
DAY_MIN = 1440


def _shift_t(s: str) -> str:
    t = datetime.strptime(s, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=timezone.utc)
    return (t + timedelta(days=1)).strftime("%Y-%m-%dT%H:%M:%SZ")


def repeat(base: dict, policy: bool) -> dict:
    out = copy.deepcopy(base)
    suffix = "_policy" if policy else ""
    out["name"] = f"{base['name'].replace('_peak', '_repeat')}{suffix}"
    out["validator"] = base["name"]
    out["description"] = (
        "pearl_street_peak run on two back-to-back evenings with the same roster and offers. "
        + ("Before each need the utility excludes providers whose Town reputation is below zero."
           if policy else "No feedback: day one's outcome does not change who can win on day two.")
        + " Does the overpromiser win again on day two, and how short is the grid?")
    out["max_time"] = base["max_time"] + DAY_MIN
    for a in out["agents"]:
        c = a["config"]
        if a["role"] == "pearl_exchange":
            c["last_tick_min"] += DAY_MIN
        elif a["role"] == "grid_operator":
            day1 = {k: c.pop(k) for k in ("post_at_min", "kw_needed", "price_cap", "gate_utc", "window")}
            day2 = dict(day1, post_at_min=day1["post_at_min"] + DAY_MIN,
                        gate_utc=_shift_t(day1["gate_utc"]),
                        window={k: _shift_t(v) for k, v in day1["window"].items()})
            c["needs"] = [day1, day2]
            if policy:
                c["skip_negative_reputation"] = True
        elif a["role"] == "flex_provider" and "offer" in c:
            o = c.pop("offer")
            c["offers"] = [o, dict(o, at_min=o["at_min"] + DAY_MIN)]
    return out


def main() -> None:
    with open(BASE, encoding="utf-8") as f:
        base = yaml.safe_load(f)
    for policy in (False, True):
        sc = repeat(base, policy)
        path = os.path.join(HERE, f"{sc['name']}.yaml")
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write("# Generated by make_repeat_scenarios.py from pearl_street_peak.yaml; do not edit.\n")
            yaml.safe_dump(sc, f, sort_keys=False, width=100)
        print(path)


if __name__ == "__main__":
    main()
